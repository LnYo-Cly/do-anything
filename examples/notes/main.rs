//! A deliberately small application for the `da` usage proof.
//!
//! One page, one JSON API and one PostgreSQL table, so a single case can check
//! the interface, the interface's HTTP call and the row it wrote. The app is an
//! example target, so it needs no dependency the package does not already have
//! and no runtime beyond the Rust toolchain that builds `da`:
//!
//! ```sh
//! export DA_TEST_POSTGRES_URL='postgres://notes@127.0.0.1:5432/notes?sslmode=disable'
//! cargo run --release --example notes
//! ```
//!
//! `README.md` next to this file explains the environment variables, the API and
//! the prepared `broken-db.patch`.

#[cfg(feature = "db")]
mod app {
    use std::io::{self, Read, Write};
    use std::net::{TcpListener, TcpStream};
    use std::sync::{Arc, Mutex};
    use std::thread;
    use std::time::Duration;

    use postgres::{Client, NoTls, Row};
    use serde_json::{Value, json};

    const INDEX_HTML: &str = include_str!("public/index.html");
    const DEFAULT_HOST: &str = "127.0.0.1";
    const DEFAULT_PORT: u16 = 3845;
    /// The largest request head the app reads before it drops the connection.
    const MAX_HEAD: usize = 64 * 1024;

    /// Every statement that returns a note selects the same columns, in the same
    /// order, and asks PostgreSQL to render the timestamp as text so the client
    /// needs no date type.
    const NOTE_COLUMNS: &str = "id, title, body, status, pinned, created_at::text AS created_at";

    const SCHEMA: &str = "\
CREATE TABLE IF NOT EXISTS notes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL UNIQUE,
    body text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT 'active',
    pinned boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
)";

    /// The connection is shared by every request thread; a request holds the
    /// lock only while it runs its one statement.
    struct State {
        client: Mutex<Client>,
    }

    struct Request {
        method: String,
        path: String,
        body: Vec<u8>,
    }

    struct Response {
        status: &'static str,
        content_type: &'static str,
        body: String,
    }

    pub fn run() {
        let Ok(url) = std::env::var("DA_TEST_POSTGRES_URL") else {
            fail(
                "DA_TEST_POSTGRES_URL is not set; export a PostgreSQL connection string such as \
                 postgres://notes@127.0.0.1:5432/notes?sslmode=disable",
            );
        };
        let mut config: postgres::Config = match url.trim().parse() {
            Ok(config) => config,
            Err(_) => fail(
                "DA_TEST_POSTGRES_URL is not a PostgreSQL connection string; \
                 it starts with postgres:// or postgresql://",
            ),
        };
        config.connect_timeout(Duration::from_secs(10));
        config.application_name("da-notes-example");
        // The connection string is never printed: it usually carries a password.
        let mut client = match config.connect(NoTls) {
            Ok(client) => client,
            Err(error) => fail(&format!(
                "cannot connect to the database named by DA_TEST_POSTGRES_URL ({}); \
                 check that the server runs and that the database exists",
                describe(&error)
            )),
        };
        if let Err(error) = prepare(&mut client) {
            fail(&format!(
                "cannot prepare the `notes` table: {}",
                describe(&error)
            ));
        }

        let host = std::env::var("NOTES_HOST").unwrap_or_else(|_| DEFAULT_HOST.to_string());
        let port = match std::env::var("NOTES_PORT") {
            Ok(text) => match text.trim().parse::<u16>() {
                Ok(port) => port,
                Err(_) => fail("NOTES_PORT is not a TCP port number"),
            },
            Err(_) => DEFAULT_PORT,
        };
        let listener = match TcpListener::bind((host.as_str(), port)) {
            Ok(listener) => listener,
            Err(error) => fail(&format!("cannot listen on {host}:{port}: {error}")),
        };
        log(&format!(
            "listening on http://{host}:{port} (database from DA_TEST_POSTGRES_URL)"
        ));

        let state = Arc::new(State {
            client: Mutex::new(client),
        });
        for stream in listener.incoming() {
            match stream {
                Ok(stream) => {
                    let state = Arc::clone(&state);
                    thread::spawn(move || serve(stream, &state));
                }
                // One connection that failed before any request arrived is the
                // client's problem; the listener keeps serving the next one.
                Err(error) => log(&format!("a connection failed: {error}")),
            }
        }
    }

    /// Creates the table, optionally empties it, and seeds two rows in an empty
    /// one so a page opened first has something to show.
    fn prepare(client: &mut Client) -> Result<(), postgres::Error> {
        client.batch_execute(SCHEMA)?;
        if std::env::var_os("NOTES_RESET").is_some() {
            client.batch_execute("TRUNCATE notes RESTART IDENTITY")?;
        }
        let count: i64 = client.query_one("SELECT count(*) FROM notes", &[])?.get(0);
        if count == 0 {
            client.batch_execute(
                "INSERT INTO notes (title, body, pinned) VALUES \
                 ('Welcome note', 'Seeded by the example app on first start.', true), \
                 ('Release checklist', 'Check the page, the API and the database row.', false)",
            )?;
        }
        Ok(())
    }

    fn serve(mut stream: TcpStream, state: &State) {
        // A client that disconnects early is normal: the browser closes
        // speculative connections without sending a request.
        let _ = answer(&mut stream, state);
    }

    fn answer(stream: &mut TcpStream, state: &State) -> io::Result<()> {
        let Some(request) = read_request(stream)? else {
            return Ok(());
        };
        let response = route(state, &request);
        write_response(stream, &response)
    }

    fn read_request(stream: &mut TcpStream) -> io::Result<Option<Request>> {
        let mut buffer = Vec::new();
        let mut chunk = [0u8; 4096];
        loop {
            if let Some(end) = find(&buffer, b"\r\n\r\n") {
                let head = String::from_utf8_lossy(&buffer[..end]).into_owned();
                let mut lines = head.split("\r\n");
                let request_line = lines.next().unwrap_or_default();
                let mut parts = request_line.split(' ');
                let method = parts.next().unwrap_or_default().to_string();
                let target = parts.next().unwrap_or_default().to_string();
                let length = lines.filter_map(content_length).next().unwrap_or(0);
                let start = end + 4;
                while buffer.len() < start + length {
                    let read = stream.read(&mut chunk)?;
                    if read == 0 {
                        break;
                    }
                    buffer.extend_from_slice(&chunk[..read]);
                }
                let stop = (start + length).min(buffer.len());
                return Ok(Some(Request {
                    method,
                    path: target.split('?').next().unwrap_or_default().to_string(),
                    body: buffer[start..stop].to_vec(),
                }));
            }
            let read = stream.read(&mut chunk)?;
            if read == 0 {
                return Ok(None);
            }
            buffer.extend_from_slice(&chunk[..read]);
            if buffer.len() > MAX_HEAD {
                return Ok(None);
            }
        }
    }

    fn content_length(line: &str) -> Option<usize> {
        let (name, value) = line.split_once(':')?;
        if !name.trim().eq_ignore_ascii_case("content-length") {
            return None;
        }
        value.trim().parse().ok()
    }

    fn route(state: &State, request: &Request) -> Response {
        let method = request.method.as_str();
        let path = request.path.as_str();
        if method == "GET" && path == "/" {
            return Response {
                status: "200 OK",
                content_type: "text/html; charset=utf-8",
                body: INDEX_HTML.to_string(),
            };
        }
        if method == "GET" && path == "/api/health" {
            return match count_notes(state) {
                Ok(count) => json_response("200 OK", &json!({"ok": true, "notes": count})),
                Err(error) => database_error(&error),
            };
        }
        if method == "GET" && path == "/api/notes" {
            return match list_notes(state) {
                Ok(notes) => json_response("200 OK", &json!({ "notes": notes })),
                Err(error) => database_error(&error),
            };
        }
        if method == "POST" && path == "/api/notes" {
            return create_note(state, request);
        }
        if method == "POST"
            && let Some(id) = note_id(path, "/pin")
        {
            return match pin_note(state, id) {
                Ok(Some(note)) => json_response("200 OK", &json!({ "note": note })),
                Ok(None) => json_response("404 Not Found", &json!({"error": "note not found"})),
                Err(error) => database_error(&error),
            };
        }
        if method == "DELETE"
            && let Some(id) = note_id(path, "")
        {
            return match delete_note(state, id) {
                Ok(true) => json_response("200 OK", &json!({ "deleted": id })),
                Ok(false) => json_response("404 Not Found", &json!({"error": "note not found"})),
                Err(error) => database_error(&error),
            };
        }
        json_response("404 Not Found", &json!({"error": "not found"}))
    }

    /// Reads `/api/notes/<digits><suffix>` and returns the id.
    fn note_id(path: &str, suffix: &str) -> Option<i64> {
        let rest = path.strip_prefix("/api/notes/")?;
        rest.strip_suffix(suffix)?.parse().ok()
    }

    fn count_notes(state: &State) -> Result<i64, postgres::Error> {
        let mut client = lock(state);
        let row = client.query_one("SELECT count(*) FROM notes", &[])?;
        Ok(row.get(0))
    }

    fn list_notes(state: &State) -> Result<Vec<Value>, postgres::Error> {
        let mut client = lock(state);
        let sql = format!("SELECT {NOTE_COLUMNS} FROM notes ORDER BY id DESC");
        let notes = client.query(&sql, &[])?;
        Ok(notes.iter().map(note_json).collect())
    }

    fn create_note(state: &State, request: &Request) -> Response {
        let title = form_value(&request.body, "title")
            .unwrap_or_default()
            .trim()
            .to_string();
        let body = form_value(&request.body, "body")
            .unwrap_or_default()
            .trim()
            .to_string();
        if title.is_empty() {
            return json_response("400 Bad Request", &json!({"error": "title is required"}));
        }
        let mut client = lock(state);
        // A title is unique, so saving the same title twice updates that note
        // instead of adding a second row: a case can be replayed unchanged.
        let sql = format!(
            "INSERT INTO notes (title, body) VALUES ($1, $2) \
             ON CONFLICT (title) DO UPDATE SET body = EXCLUDED.body, status = 'active' \
             RETURNING {NOTE_COLUMNS}"
        );
        match client.query_one(&sql, &[&title, &body]) {
            Ok(row) => json_response("201 Created", &json!({ "note": note_json(&row) })),
            Err(error) => database_error(&error),
        }
    }

    fn pin_note(state: &State, id: i64) -> Result<Option<Value>, postgres::Error> {
        let mut client = lock(state);
        let sql =
            format!("UPDATE notes SET pinned = NOT pinned WHERE id = $1 RETURNING {NOTE_COLUMNS}");
        let rows = client.query(&sql, &[&id])?;
        Ok(rows.first().map(note_json))
    }

    fn delete_note(state: &State, id: i64) -> Result<bool, postgres::Error> {
        let mut client = lock(state);
        Ok(client.execute("DELETE FROM notes WHERE id = $1", &[&id])? > 0)
    }

    fn note_json(row: &Row) -> Value {
        json!({
            "id": row.get::<_, i64>("id"),
            "title": row.get::<_, String>("title"),
            "body": row.get::<_, String>("body"),
            "status": row.get::<_, String>("status"),
            "pinned": row.get::<_, bool>("pinned"),
            "created_at": row.get::<_, String>("created_at"),
        })
    }

    /// A connection that panicked while holding the lock is still usable: the
    /// panic did not corrupt the statement the client is about to send.
    fn lock(state: &State) -> std::sync::MutexGuard<'_, Client> {
        state
            .client
            .lock()
            .unwrap_or_else(|poison| poison.into_inner())
    }

    /// Reads one `application/x-www-form-urlencoded` field.
    fn form_value(body: &[u8], name: &str) -> Option<String> {
        let text = String::from_utf8_lossy(body);
        text.split('&').find_map(|pair| {
            let (key, value) = pair.split_once('=').unwrap_or((pair, ""));
            (percent_decode(key) == name).then(|| percent_decode(value))
        })
    }

    fn percent_decode(text: &str) -> String {
        let bytes = text.as_bytes();
        let mut decoded = Vec::with_capacity(bytes.len());
        let mut index = 0;
        while index < bytes.len() {
            match bytes[index] {
                b'+' => {
                    decoded.push(b' ');
                    index += 1;
                }
                b'%' if index + 2 < bytes.len() => {
                    match (hex_value(bytes[index + 1]), hex_value(bytes[index + 2])) {
                        (Some(high), Some(low)) => {
                            decoded.push(high * 16 + low);
                            index += 3;
                        }
                        _ => {
                            decoded.push(b'%');
                            index += 1;
                        }
                    }
                }
                byte => {
                    decoded.push(byte);
                    index += 1;
                }
            }
        }
        String::from_utf8_lossy(&decoded).into_owned()
    }

    fn hex_value(byte: u8) -> Option<u8> {
        match byte {
            b'0'..=b'9' => Some(byte - b'0'),
            b'a'..=b'f' => Some(byte - b'a' + 10),
            b'A'..=b'F' => Some(byte - b'A' + 10),
            _ => None,
        }
    }

    fn find(haystack: &[u8], needle: &[u8]) -> Option<usize> {
        haystack
            .windows(needle.len())
            .position(|window| window == needle)
    }

    fn write_response(stream: &mut TcpStream, response: &Response) -> io::Result<()> {
        let head = format!(
            "HTTP/1.1 {}\r\nContent-Type: {}\r\nContent-Length: {}\r\n\
             Cache-Control: no-store\r\nConnection: close\r\n\r\n",
            response.status,
            response.content_type,
            response.body.len()
        );
        stream.write_all(head.as_bytes())?;
        stream.write_all(response.body.as_bytes())?;
        stream.flush()
    }

    fn json_response(status: &'static str, value: &Value) -> Response {
        let body = serde_json::to_string(value)
            .unwrap_or_else(|_| "{\"error\":\"the response could not be serialized\"}".to_string());
        Response {
            status,
            content_type: "application/json; charset=utf-8",
            body,
        }
    }

    fn database_error(error: &postgres::Error) -> Response {
        json_response(
            "503 Service Unavailable",
            &json!({ "error": format!("database error: {}", describe(error)) }),
        )
    }

    /// The whole cause chain: a `postgres::Error` names only its outer layer.
    fn describe(error: &postgres::Error) -> String {
        let mut text = error.to_string();
        let mut source = std::error::Error::source(error);
        while let Some(cause) = source {
            text.push_str(": ");
            text.push_str(&cause.to_string());
            source = cause.source();
        }
        text
    }

    fn log(message: &str) {
        let _ = writeln!(io::stderr(), "notes: {message}");
    }

    fn fail(message: &str) -> ! {
        let _ = writeln!(io::stderr(), "notes: {message}");
        std::process::exit(1);
    }
}

#[cfg(feature = "db")]
fn main() {
    app::run();
}

#[cfg(not(feature = "db"))]
fn main() {
    // The rows are written through the `postgres` client, which the `db`
    // feature provides. Building the package without that feature must still
    // succeed, because `--all-targets` compiles every example.
    use std::io::Write;
    let _ = writeln!(
        std::io::stderr(),
        "notes: this example needs the `db` feature; run `cargo run --example notes` \
         with the default features"
    );
    std::process::exit(1);
}
